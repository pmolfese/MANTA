import Foundation

public struct GeoScanTextPoint: Sendable {
    public var label: String
    public var coordinate: Coordinate3D
    public var isEstimated: Bool

    public init(label: String, coordinate: Coordinate3D, isEstimated: Bool = true) {
        self.label = label
        self.coordinate = coordinate
        self.isEstimated = isEstimated
    }
}

/// Matches the supplied GeoScan five-column text syntax. It does not reproduce
/// a scanner-specific frame or claim the points were acquired with GeoScan.
public enum GeoScanTextExporter {
    public static func export(
        _ points: [GeoScanTextPoint], sourceUnit: DistanceUnit,
        coordinateFrame: String, labellingTemplate: String
    ) -> String {
        let header = [
            "# File format: ElectrodeName X Y Z Estimated",
            "# Generated by MANTA; coordinates describe visible disc/cup centers or fiducials.",
            "# Units = cm",
            "# CoordinateFrame = \(token(coordinateFrame))",
            "# Estimated = 0 only for explicitly measured points; 1 for estimated or unverified provenance.",
            "LabellingTemplate = \(token(labellingTemplate))"
        ]
        let rows = points.map { point in
            let p = point.coordinate.converted(from: sourceUnit, to: .centimeters)
            return [token(point.label), number(p.x), number(p.y), number(p.z),
                    point.isEstimated ? "1" : "0"].joined(separator: " ")
        }
        return (header + rows).joined(separator: "\n") + "\n"
    }

    private static func number(_ value: Double) -> String {
        String(format: "%.6f", locale: Locale(identifier: "en_US_POSIX"), value)
    }

    private static func token(_ value: String) -> String {
        value.split(whereSeparator: { $0.isWhitespace }).joined(separator: "_")
    }
}
